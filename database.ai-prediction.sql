-- Additive migration for rule-based FoodGuard analysis history.
-- This does not modify the existing sensor_data table.
create table if not exists public.prediction_history (
    id bigint generated by default as identity primary key,
    analysis_type text not null check (analysis_type = 'food_spoilage'),
    assessment_key text not null check (assessment_key in ('within_baseline', 'needs_observation', 'potential_risk')),
    overall_assessment text not null,
    sensor_snapshot jsonb not null,
    detected_anomalies jsonb not null default '[]'::jsonb,
    recommendations jsonb not null default '[]'::jsonb,
    analyzed_at timestamptz not null default now()
);

create index if not exists prediction_history_analyzed_at_desc_idx
    on public.prediction_history (analyzed_at desc);

alter table public.prediction_history enable row level security;